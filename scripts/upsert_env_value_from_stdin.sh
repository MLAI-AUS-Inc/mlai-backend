#!/usr/bin/env bash
set -euo pipefail

key="${1:-}"
case "$key" in
  VALLEY_MCP_UNIFIED_ALIAS_ENABLED|MLAI_MCP_NATIVE_AGENTS_ENABLED|AGENT_RUNTIME_ENABLED|AGENT_RUNTIME_NATIVE_ENABLED|AGENT_RUNTIME_NATIVE_REPLIES_ENABLED|AGENT_RUNTIME_MCP_EVENTS_ENABLED|AGENT_RUNTIME_NATIVE_COMMUNITIES|AGENT_RUNTIME_DOT_SETUP_URL|AGENT_RUNTIME_NATIVE_PERSONAL_LIMIT|AGENT_RUNTIME_COMMUNITY_ENABLED|AGENT_RUNTIME_PERSONAL_CONTEXT_ENABLED|AGENT_RUNTIME_NATIVE_ALWAYS_ADMIT|AGENT_RUNTIME_NATIVE_QUEUE_TTL_MINUTES|AGENT_RUNTIME_NATIVE_ADMISSION_DAILY_CAP|AGENT_RUNTIME_NATIVE_LIMIT_TIMEZONE|AGENT_RUNTIME_NATIVE_BACKLOG_REPLAY|AGENT_RUNTIME_MCP_EVENTS_LEASE_POLICY|AGENT_RUNTIME_NATIVE_DURABLE_WATCH|AGENT_RUNTIME_NATIVE_DENIAL_GRACE_SECONDS|AGENT_RUNTIME_NATIVE_UNIFIED_GRACE_SECONDS|AGENT_RUNTIME_NATIVE_RENEWAL_ENABLED|MLAI_MCP_AGENT_GRANT_EXTENSION_ENABLED|MLAI_MCP_REFRESH_REPLAY_GRACE_SECONDS|\
  COMMUNITY_CHAT_MEMBER_ACCOUNTS_ENABLED|COMMUNITY_CHAT_INBOX_ERASURE_ENABLED|\
  COMMUNITY_BRIDGE_DEPENDENCY_VERDICTS_ENABLED|MESSAGE_SYNC_OPEN_PRIORITY_ENABLED|MESSAGE_SYNC_UNREAD_PREFETCH_ENABLED|MESSAGE_SYNC_RECENT_HISTORY_ENABLED|MESSAGE_SYNC_TARGETED_STAGED_ROUTING|\
  MESSAGE_SYNC_TARGETED_READ_POLLING|MESSAGE_SYNC_INBOX_READ_EXPORT|\
  MESSAGE_SYNC_INBOX_CURSOR_PUSH|MESSAGE_SYNC_INBOX_MENTIONS|MESSAGE_SYNC_RELAY_READ_COUNTS) ;;
  MESSAGE_SYNC_DEVICE_FANOUT_BATCH|MESSAGE_SYNC_UNREAD_PREFETCH_PER_HOUR|MESSAGE_SYNC_ENABLED|MESSAGE_SYNC_QUIET_HEAD_BACKOFF_ENABLED|SLACK_OWNER_INVENTORY_ENABLED|MESSAGE_SYNC_SLACK_APP_ID|MESSAGE_SYNC_SLACK_USER_APP_ID|MESSAGE_SYNC_SLACK_BOT_WORKSPACE_ID|MESSAGE_SYNC_SLACK_DISTRIBUTION|SLACK_MEMBER_CHANNEL_ALLOWED_IDS|\
  LINEAR_MEETING_REQUIRED_TEAM_KEYS|LINEAR_CHANNEL_ISSUE_BINDINGS_JSON|LINEAR_CHANNEL_ISSUE_MAX_COMMENTS|LINEAR_CHANNEL_ISSUE_WRITES_ENABLED|\
  MLAI_MCP_ENABLED|MLAI_MCP_COMMUNITY_ENABLED|MLAI_MCP_COMMUNITY_RELAY_URL|MLAI_MCP_COMMUNITY_SECRET|MLAI_MCP_CLIENT_INSTALL_URLS|VALLEY_MCP_ENABLED|VALLEY_MCP_PUBLIC_BASE_URL|VALLEY_MCP_DOMAIN_VERIFICATION_TOKEN|COMMUNITY_CHAT_STARTUP_UPDATES_ENABLED|\
  WEBSITE_CONNECTION_WRITE_MODE|WEBSITE_CONNECTION_CANARY_DOMAINS|APPROVED_MIGRATION_PLAN_SHA256|\
  COMMUNITY_CHAT_CRM_ENABLED|CRM_LUMA_SYNC_ENABLED|CRM_SENDING_ENABLED|CRM_SMS_ENABLED|CRM_WHATSAPP_ENABLED|\
  CRM_WARMUP_ENABLED|CRM_WARMUP_RUN_ID|CRM_RESEND_MONITORED_SENDERS|LISTMONK_BASE_URL|LISTMONK_API_USER|TWILIO_MESSAGING_SERVICE_SID|\
  ARTICLES_FREE_SETUP_RESEARCH_ENABLED|ARTICLES_FREE_FIRST_ARTICLE_ENABLED|ARTICLES_FIRST_ARTICLE_GOAL_ENABLED|ARTICLES_FOUNDER_JOURNEY_ALERTS_ENABLED|\
  ARTICLES_FREE_SETUP_AUTOFILL_DAILY_CAP|ARTICLES_FREE_SETUP_BASELINE_DAILY_CAP|ARTICLES_FREE_FIRST_ARTICLE_DAILY_CAP|ARTICLES_FREE_FIRST_ARTICLE_SPIKE_THRESHOLD|\
  CONTENT_FACTORY_INTERACTIVE_QUEUE_SLOTS|ARTICLES_FOUNDER_JOURNEY_ALERTS_MAX_PER_TICK|ARTICLES_FOUNDER_JOURNEY_ALERTS_SINCE|ARTICLES_WORKSHOP_WINDOWS|\
  CONTENT_FACTORY_PORTABLE_PREVIEW_REARM|HOSTED_PUBLISH_REQUIRES_RENDERED_PREVIEW|\
  ARTICLES_SNAPSHOT_MERGE_BY_MEANING_ENABLED|ARTICLES_RUN_EVENTS_ENABLED|\
  MY_STARTUP_FOUNDER_JOURNEY_V2_ENABLED|MY_STARTUP_FOUNDER_JOURNEY_API_ENABLED|MY_STARTUP_FOUNDER_JOURNEY_OPT_IN_ENABLED|\
  COMMUNITY_CHAT_ONE_STEP_JOIN_ENABLED|COMMUNITY_CHAT_INVITE_TOKENS_ENABLED|MY_STARTUP_PENDING_MEMBER_ACCESS_ENABLED|\
  COMMUNITY_CHAT_REVIEW_CLEARED_EMAIL_ENABLED|COMMUNITY_CHAT_DEVICE_AUTH_V2_ENABLED|MY_STARTUP_ONE_FIELD_START_ENABLED|\
  MY_STARTUP_NO_WEBSITE_ARTICLES_ENABLED|ARTICLES_FIRST_ARTICLE_CARD_ENABLED|ARTICLES_COPY_READY_BEFORE_VERIFICATION_ENABLED|\
  ARTICLES_DRAFT_READY_NOTIFICATIONS_ENABLED|ARTICLES_COPY_WITHOUT_PREVIEW_ENABLED|ARTICLES_DRAFT_TOOLS_ENABLED|ARTICLES_LIVE_URL_VERIFICATION_ENABLED|\
  MY_STARTUP_GITHUB_CALLBACK_REDIRECTS_ENABLED|COMMUNITY_CHAT_INVITE_TOKEN_DEFAULT_TTL_HOURS|COMMUNITY_CHAT_INVITE_TOKEN_MAX_TTL_HOURS|\
  COMMUNITY_CHAT_DEVICE_AUTH_MAX_LIFETIME_SECONDS|MY_STARTUP_FOUNDER_JOURNEY_V2_LAUNCHED_AT|MY_STARTUP_FOUNDER_JOURNEY_V2_DISABLED_ORGANIZATIONS|\
  COMMUNITY_CHAT_INVITE_RESOLVE_RATE|\
  AUTH_THROTTLE_IP_CODE_REQUESTS_PER_HOUR|AUTH_THROTTLE_IP_VERIFY_PER_10M|AUTH_THROTTLE_IP_PASSWORD_PER_10M|AUTH_THROTTLE_IP_BOOTSTRAP_AUTHENTICATED_PER_10M|AUTH_THROTTLE_IP_DEVICE_AUTH_PER_10M) ;;
  *)
    echo "Unsupported production environment key" >&2
    exit 64
    ;;
esac

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$repo_root"
umask 077
# Preserve trailing newlines until validation; ordinary command substitution
# would strip them and accept a malformed multi-line value as its prefix.
value="$(
  if [[ "$key" == "SLACK_MEMBER_CHANNEL_ALLOWED_IDS" ]]; then
    # Validate the original input before Bash can discard NUL bytes. Reuse the
    # deployment validator with only this value, without reading host settings.
    python3 -c 'import runpy, sys; value = sys.stdin.read(); runpy.run_path("scripts/validate_message_sync_deploy_config.py")["validate"]({"SLACK_MEMBER_CHANNEL_ALLOWED_IDS": value}); sys.stdout.write(value)' || exit $?
  else
    cat
  fi
  printf '\037'
)"
value="${value%$'\037'}"

if [[ "$value" == *$'\n'* || "$value" == *$'\r'* ]]; then
  echo "Invalid single-line payload for ${key}" >&2
  exit 1
fi

case "$key" in
  VALLEY_MCP_UNIFIED_ALIAS_ENABLED)
    printf '%s' "$value" | python3 scripts/validate_valley_mcp_deploy_config.py --stdin "$key"
    ;;
  MLAI_MCP_NATIVE_AGENTS_ENABLED|AGENT_RUNTIME_ENABLED|AGENT_RUNTIME_NATIVE_ENABLED|AGENT_RUNTIME_NATIVE_REPLIES_ENABLED|AGENT_RUNTIME_MCP_EVENTS_ENABLED|AGENT_RUNTIME_NATIVE_COMMUNITIES|AGENT_RUNTIME_DOT_SETUP_URL|AGENT_RUNTIME_NATIVE_PERSONAL_LIMIT|AGENT_RUNTIME_COMMUNITY_ENABLED|AGENT_RUNTIME_PERSONAL_CONTEXT_ENABLED|AGENT_RUNTIME_NATIVE_ALWAYS_ADMIT|AGENT_RUNTIME_NATIVE_QUEUE_TTL_MINUTES|AGENT_RUNTIME_NATIVE_ADMISSION_DAILY_CAP|AGENT_RUNTIME_NATIVE_LIMIT_TIMEZONE|AGENT_RUNTIME_NATIVE_BACKLOG_REPLAY|AGENT_RUNTIME_MCP_EVENTS_LEASE_POLICY|AGENT_RUNTIME_NATIVE_DURABLE_WATCH|AGENT_RUNTIME_NATIVE_DENIAL_GRACE_SECONDS|AGENT_RUNTIME_NATIVE_UNIFIED_GRACE_SECONDS|AGENT_RUNTIME_NATIVE_RENEWAL_ENABLED|MLAI_MCP_AGENT_GRANT_EXTENSION_ENABLED|MLAI_MCP_REFRESH_REPLAY_GRACE_SECONDS)
    printf '%s' "$value" | python3 scripts/validate_native_agent_deploy_config.py --stdin "$key"
    ;;
  WEBSITE_CONNECTION_WRITE_MODE|WEBSITE_CONNECTION_CANARY_DOMAINS|APPROVED_MIGRATION_PLAN_SHA256)
    printf '%s' "$value" | python3 scripts/validate_website_deploy_config.py --stdin "$key"
    ;;
  COMMUNITY_CHAT_CRM_ENABLED|CRM_LUMA_SYNC_ENABLED|CRM_SENDING_ENABLED|CRM_SMS_ENABLED|CRM_WHATSAPP_ENABLED|\
  CRM_WARMUP_ENABLED|CRM_WARMUP_RUN_ID|CRM_RESEND_MONITORED_SENDERS|LISTMONK_BASE_URL|LISTMONK_API_USER|TWILIO_MESSAGING_SERVICE_SID)
    printf '%s' "$value" | python3 scripts/validate_crm_deploy_config.py --stdin "$key"
    ;;
  ARTICLES_FREE_SETUP_RESEARCH_ENABLED|ARTICLES_FREE_FIRST_ARTICLE_ENABLED|ARTICLES_FIRST_ARTICLE_GOAL_ENABLED|ARTICLES_FOUNDER_JOURNEY_ALERTS_ENABLED|\
  ARTICLES_FREE_SETUP_AUTOFILL_DAILY_CAP|ARTICLES_FREE_SETUP_BASELINE_DAILY_CAP|ARTICLES_FREE_FIRST_ARTICLE_DAILY_CAP|ARTICLES_FREE_FIRST_ARTICLE_SPIKE_THRESHOLD|\
  CONTENT_FACTORY_INTERACTIVE_QUEUE_SLOTS|ARTICLES_FOUNDER_JOURNEY_ALERTS_MAX_PER_TICK|ARTICLES_FOUNDER_JOURNEY_ALERTS_SINCE|ARTICLES_WORKSHOP_WINDOWS|\
  CONTENT_FACTORY_PORTABLE_PREVIEW_REARM|HOSTED_PUBLISH_REQUIRES_RENDERED_PREVIEW|\
  ARTICLES_SNAPSHOT_MERGE_BY_MEANING_ENABLED|ARTICLES_RUN_EVENTS_ENABLED|\
  MY_STARTUP_FOUNDER_JOURNEY_V2_ENABLED|MY_STARTUP_FOUNDER_JOURNEY_API_ENABLED|MY_STARTUP_FOUNDER_JOURNEY_OPT_IN_ENABLED|\
  COMMUNITY_CHAT_ONE_STEP_JOIN_ENABLED|COMMUNITY_CHAT_INVITE_TOKENS_ENABLED|MY_STARTUP_PENDING_MEMBER_ACCESS_ENABLED|\
  COMMUNITY_CHAT_REVIEW_CLEARED_EMAIL_ENABLED|COMMUNITY_CHAT_DEVICE_AUTH_V2_ENABLED|MY_STARTUP_ONE_FIELD_START_ENABLED|\
  MY_STARTUP_NO_WEBSITE_ARTICLES_ENABLED|ARTICLES_FIRST_ARTICLE_CARD_ENABLED|ARTICLES_COPY_READY_BEFORE_VERIFICATION_ENABLED|\
  ARTICLES_DRAFT_READY_NOTIFICATIONS_ENABLED|ARTICLES_COPY_WITHOUT_PREVIEW_ENABLED|ARTICLES_DRAFT_TOOLS_ENABLED|ARTICLES_LIVE_URL_VERIFICATION_ENABLED|\
  MY_STARTUP_GITHUB_CALLBACK_REDIRECTS_ENABLED|COMMUNITY_CHAT_INVITE_TOKEN_DEFAULT_TTL_HOURS|COMMUNITY_CHAT_INVITE_TOKEN_MAX_TTL_HOURS|\
  COMMUNITY_CHAT_DEVICE_AUTH_MAX_LIFETIME_SECONDS|MY_STARTUP_FOUNDER_JOURNEY_V2_LAUNCHED_AT|MY_STARTUP_FOUNDER_JOURNEY_V2_DISABLED_ORGANIZATIONS|\
  COMMUNITY_CHAT_INVITE_RESOLVE_RATE|\
  AUTH_THROTTLE_IP_CODE_REQUESTS_PER_HOUR|AUTH_THROTTLE_IP_VERIFY_PER_10M|AUTH_THROTTLE_IP_PASSWORD_PER_10M|AUTH_THROTTLE_IP_BOOTSTRAP_AUTHENTICATED_PER_10M|AUTH_THROTTLE_IP_DEVICE_AUTH_PER_10M)
    printf '%s' "$value" | python3 scripts/validate_articles_deploy_config.py --stdin "$key"
    ;;
  MLAI_MCP_ENABLED|MLAI_MCP_COMMUNITY_ENABLED|MLAI_MCP_COMMUNITY_RELAY_URL|MLAI_MCP_COMMUNITY_SECRET|MLAI_MCP_CLIENT_INSTALL_URLS|VALLEY_MCP_ENABLED|VALLEY_MCP_PUBLIC_BASE_URL|VALLEY_MCP_DOMAIN_VERIFICATION_TOKEN|COMMUNITY_CHAT_STARTUP_UPDATES_ENABLED)
    printf '%s' "$value" | python3 scripts/validate_valley_mcp_deploy_config.py --stdin "$key"
    ;;
  MESSAGE_SYNC_ENABLED|MESSAGE_SYNC_QUIET_HEAD_BACKOFF_ENABLED|SLACK_OWNER_INVENTORY_ENABLED|\
  COMMUNITY_CHAT_MEMBER_ACCOUNTS_ENABLED|COMMUNITY_CHAT_INBOX_ERASURE_ENABLED|\
  COMMUNITY_BRIDGE_DEPENDENCY_VERDICTS_ENABLED|MESSAGE_SYNC_OPEN_PRIORITY_ENABLED|MESSAGE_SYNC_UNREAD_PREFETCH_ENABLED|MESSAGE_SYNC_RECENT_HISTORY_ENABLED|MESSAGE_SYNC_TARGETED_STAGED_ROUTING|\
  MESSAGE_SYNC_TARGETED_READ_POLLING|MESSAGE_SYNC_INBOX_READ_EXPORT|\
  MESSAGE_SYNC_INBOX_CURSOR_PUSH|MESSAGE_SYNC_INBOX_MENTIONS|MESSAGE_SYNC_RELAY_READ_COUNTS)
    [[ "$value" == "true" || "$value" == "false" ]] || {
      echo "${key} must be true or false" >&2
      exit 1
    }
    ;;
  MESSAGE_SYNC_DEVICE_FANOUT_BATCH)
    [[ "$value" =~ ^(0|[1-9][0-9]?)$ ]] && [[ "$value" -le 50 ]] || {
      echo "${key} must be an integer from 0 to 50" >&2
      exit 1
    }
    ;;
  MESSAGE_SYNC_UNREAD_PREFETCH_PER_HOUR)
    [[ "$value" =~ ^[1-9][0-9]{0,2}$ ]] && [[ "$value" -le 256 ]] || {
      echo "${key} must be an integer from 1 to 256" >&2
      exit 1
    }
    ;;
  MESSAGE_SYNC_SLACK_APP_ID|MESSAGE_SYNC_SLACK_USER_APP_ID)
    [[ "$value" =~ ^A[A-Z0-9]+$ ]] || {
      echo "${key} must be a Slack app ID" >&2
      exit 1
    }
    ;;
  MESSAGE_SYNC_SLACK_BOT_WORKSPACE_ID)
    [[ "$value" =~ ^T[A-Z0-9]+$ ]] || {
      echo "${key} must be a Slack workspace ID" >&2
      exit 1
    }
    ;;
  MESSAGE_SYNC_SLACK_DISTRIBUTION)
    [[ "$value" == "restricted" || "$value" == "internal" || "$value" == "marketplace" ]] || {
      echo "Invalid MESSAGE_SYNC_SLACK_DISTRIBUTION" >&2
      exit 1
    }
    ;;
  LINEAR_MEETING_REQUIRED_TEAM_KEYS)
    [[ "$value" =~ ^[A-Za-z0-9_-]+(,[A-Za-z0-9_-]+)*$ ]] || {
      echo "LINEAR_MEETING_REQUIRED_TEAM_KEYS must be a comma-separated team-key list" >&2
      exit 1
    }
    ;;
  LINEAR_CHANNEL_ISSUE_BINDINGS_JSON)
    LINEAR_API_KEY="validation-placeholder-at-least-32-characters" \
      LINEAR_MEETING_REQUIRED_TEAM_KEYS="TECH,STU,MLA" \
      LINEAR_CHANNEL_ISSUE_BINDINGS_JSON="$value" \
      LINEAR_CHANNEL_ISSUE_MAX_COMMENTS=250 \
      python3 scripts/validate_linear_channel_issue_deploy_config.py
    ;;
  LINEAR_CHANNEL_ISSUE_MAX_COMMENTS)
    [[ "$value" =~ ^[1-9][0-9]*$ ]] || {
      echo "LINEAR_CHANNEL_ISSUE_MAX_COMMENTS must be a positive integer" >&2
      exit 1
    }
    ;;
  LINEAR_CHANNEL_ISSUE_WRITES_ENABLED)
    [[ "$value" == "true" || "$value" == "false" ]] || {
      echo "LINEAR_CHANNEL_ISSUE_WRITES_ENABLED must be true or false" >&2
      exit 1
    }
    ;;
esac

if [[ -z "$value" && "$key" != "WEBSITE_CONNECTION_CANARY_DOMAINS" && "$key" != "APPROVED_MIGRATION_PLAN_SHA256" && "$key" != "SLACK_MEMBER_CHANNEL_ALLOWED_IDS" ]]; then
  echo "Invalid empty payload for ${key}" >&2
  exit 1
fi

# A second plugin's proof must not silently replace the proof already served.
if [[ "$key" == "VALLEY_MCP_DOMAIN_VERIFICATION_TOKEN" && -f .env ]]; then
  existing_challenge="$(sed -n 's/^VALLEY_MCP_DOMAIN_VERIFICATION_TOKEN=//p' .env)"
  if [[ -n "$existing_challenge" && "$existing_challenge" != "$value" ]]; then
    echo "Existing OpenAI ownership proof differs; explicit reconciliation is required" >&2
    exit 1
  fi
fi

tmp="$(mktemp .env.managed-value.XXXXXX)"
if [[ -f .env ]]; then
  grep -v "^${key}=" .env > "$tmp" || true
fi
printf '%s=%s\n' "$key" "$value" >> "$tmp"
chmod 600 "$tmp"
mv "$tmp" .env
